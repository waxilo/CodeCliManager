//! 单实例约束：一个进程只允许存在一份，重复启动 = 打开已开启的那个应用。
//!
//! ## 行为
//!
//! 第二次启动（双击快捷方式 / 开始菜单 / 任务栏 / 命令行）会被本机单实例机制识别，
//! 新进程**立即退出**，并把「有人想启动我」这件事转交给已在运行的进程；
//! 后者把主窗口从托盘或最小化状态唤到前台。于是不再并存两个进程、两份托盘图标、
//! 两套 Kiro 代理与常驻会话。
//!
//! ## 为什么唤起动作交给已运行进程
//!
//! 把窗口拉到前台需要操作**已存在窗口的句柄**与 tao 的窗口状态，只有持有窗口的进程能做；
//! 且必须在主线程做——tao 的窗口标志在主线程同步更新，`set_focus` 依赖这些标志判断窗口
//! 是否可聚焦。插件在 Windows 上通过隐藏窗口的 `WM_COPYDATA` 把参数送进来，回调天然运行在
//! 主线程，正好满足这个前提。
//!
//! ## 与自动更新重启的关系
//!
//! 更新重启（`process:allow-restart` → `RunEvent::Exit` → 释放单实例锁 → 再 spawn 新进程）
//! 是先解锁再拉起新进程的：新进程不会再看到「已运行实例」，因此不会把正在退出的旧进程
//! 误判为单例而自杀；Windows 的 NSIS 安装器同样先把旧进程结束掉再拉起新版本。

use tauri::plugin::TauriPlugin;
use tauri::{AppHandle, Wry};

/// 单实例插件。**必须最先注册**：它要在其它插件/窗口建立之前完成「我是第几个实例」的判定。
pub(crate) fn plugin() -> TauriPlugin<Wry> {
    tauri_plugin_single_instance::init(|app: &AppHandle, args, cwd| {
        // args[0] 是可执行文件路径，后面才是用户真正的参数；当前没有命令行接口，仅记录用于排查。
        eprintln!("[single-instance] 已有实例在运行，转交唤起主窗口（args={args:?}, cwd={cwd}）");
        crate::window::show_main_window(app);
    })
}
